import type { LocalizedInstructionSteps, MeditationPractice } from "@/lib/models";
import { l } from "@/lib/utils";
import { base } from "../shared";

type PracticeInput = {
  id: string;
  nameEs: string;
  nameEn: string;
  category: string;
  summaryEs: string;
  summaryEn: string;
  level: MeditationPractice["level"];
  minutes: number;
  objectiveEs: string;
  objectiveEn: string;
  preparationEs: string;
  preparationEn: string;
  steps: LocalizedInstructionSteps;
  instructionsEs: string;
  instructionsEn: string;
  postureEs: string;
  postureEn: string;
  benefitsEs: string;
  benefitsEn: string;
  difficultiesEs: string;
  difficultiesEn: string;
  tipsEs: string;
  tipsEn: string;
  safetyEs?: string;
  safetyEn?: string;
  relatedIds?: string[];
  guidedScript?: ReturnType<typeof l>;
};

function practice(input: PracticeInput): MeditationPractice {
  return {
    ...base(
      input.id,
      input.nameEs,
      input.nameEn,
      input.category,
      l(input.summaryEs, input.summaryEn),
    ),
    kind: "meditation",
    level: input.level,
    duration: input.minutes * 60,
    objective: l(input.objectiveEs, input.objectiveEn),
    preparation: l(input.preparationEs, input.preparationEn),
    instructions: l(input.instructionsEs, input.instructionsEn),
    instructionSteps: input.steps,
    posture: l(input.postureEs, input.postureEn),
    benefits: l(input.benefitsEs, input.benefitsEn),
    difficulties: l(input.difficultiesEs, input.difficultiesEn),
    tips: l(input.tipsEs, input.tipsEn),
    safety: l(
      input.safetyEs ??
        "Mantén la práctica como una opción y dentro de tu comodidad. Si aparece malestar, dolor, mareo o sensación de desconexión, abre los ojos, oriéntate en la habitación y detente. La meditación no sustituye la atención médica o psicológica.",
      input.safetyEn ??
        "Keep the practice optional and within your comfort. If it brings distress, pain, dizziness, or a sense of disconnection, open your eyes, orient to the room, and stop. Meditation is not a substitute for medical or psychological care.",
    ),
    relatedIds: input.relatedIds ?? [],
    ...(input.guidedScript ? { guidedScript: input.guidedScript } : {}),
  };
}

